# Lesson No.8: Types of Operators

# + - Addition
# - - Subtraction
# * - Multiplication
# / - Division
# % - Modulus (Remainder)
# // - Divisor (Quotient)
# ** - Exponent (Power)

add = 5 + 9
sub = 9 - 5
mul = 5 * 9
div = 10 / 5
mod = 10 % 3
divisor = 10 // 3
exp_sqr = 2 ** 2
exp_cube = 2 ** 3
print(add)
print(sub)
print(mul)
print(div)
print(mod)
print(divisor)
print(exp_sqr)
print(exp_cube)

# Assignment Operators
# = - Assigns value from right side to left side
# += - Adds right operand to left operand and assigns the result to left operand
# -= - Subtracts right operand from left operand and assigns the result to left operand
# *= - Multiplies right operand with left operand and assigns the result to left operand
# /= - Divides left operand by right operand and assigns the result to left operand
# %= - Takes modulus using two operands and assigns the result to left operand
# //= - Divides left operand by right operand and assigns the result to left operand
# **= - Performs exponential (power) calculation on operators and assigns value to left operand
# &= (bitwise AND and assign)
# |= (bitwise OR and assign)
# ^= (bitwise XOR and assign)
# >>= (bitwise right shift and assign)
# <<= (bitwise left shift and assign)

# Comparison Operators
# == - Compares two operands and checks if they are equal
# != - Compares two operands and checks if they are not equal
# > - Compares two operands and checks if left operand is greater than right operand
# < - Compares two operands and checks if left operand is less than right operand
# >= - Compares two operands and checks if left operand is greater than or equal to right operand
# <= - Compares two operands and checks if left operand is less than or equal to right operand

# Logical Operators
# and - Returns True if both operands are true
# or - Returns True if either operand is true
# not - Returns True if the operand is false

# Identity Operators
# is - Returns True if both operands are the same object
# is not - Returns True if both operands are not the same object

# Membership Operators
# in - Returns True if the value is found in the sequence
# not in - Returns True if the value is not found in the sequence

# Bitwise Operators
# & - Bitwise AND
# | - Bitwise OR
# ^ - Bitwise XOR
# ~ - Bitwise NOT
# << - Bitwise left shift
# >> - Bitwise right shift

# Round off function
# round() - Rounds a floating point number to the nearest integer
# abs() - Returns the absolute value of a number

print(round(2.9))
print(abs(-6))